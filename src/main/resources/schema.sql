-- TripVault schema. Constraints in the database are the last line of defense:
-- even if application validation were bypassed, invalid rows are rejected here.
CREATE TABLE IF NOT EXISTS trips (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_username  VARCHAR(50)  NOT NULL,
    destination     VARCHAR(100) NOT NULL,
    departure_date  DATE         NOT NULL,
    return_date     DATE         NOT NULL,
    passport_number VARCHAR(255) NOT NULL,   -- AES-256-GCM ciphertext ("v1:..."), never plaintext
    created_at      TIMESTAMP    NOT NULL,
    CONSTRAINT chk_trip_dates CHECK (return_date >= departure_date)
);

-- Every query filters by owner, so index it.
CREATE INDEX IF NOT EXISTS idx_trips_owner ON trips (owner_username);

-- User accounts for Spring Security. Passwords are stored ONLY as BCrypt hashes.
CREATE TABLE IF NOT EXISTS app_users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,   -- BCrypt, e.g. $2a$12$... (60 chars)
    role            VARCHAR(20)  NOT NULL,
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    failed_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until    TIMESTAMP,
    last_login_at   TIMESTAMP,
    CONSTRAINT chk_user_role CHECK (role IN ('USER', 'ADMIN'))
);
